export function helpBtn(key, extraClass = '') {
  return h('button', { class: 'qbtn ' + extraClass, title: '这是什么？', 'aria-label': '帮助', onclick: (e) => { e.stopPropagation(); showHelp(key); }, html: icon('help') });
}

export function showHelp(key) {
  const e = HELP[key];
  if (!e) return;
  const body = h('div', { class: 'helpbody' },
    e.s ? h('p', { class: 'lead' }, e.s) : null,
    e.b ? h('div', { html: e.b }) : null,
    e.ill ? h('div', { class: 'illuswrap', html: e.ill }) : null,
    e.tips && e.tips.length ? h('div', { class: 'tips' }, h('b', {}, '小提示'), h('ul', {}, e.tips.map((t) => h('li', {}, t)))) : null);
  modal(e.t, body, [{ label: '知道了', value: 1, primary: true }]);
}

export function helpCenter() {
  const list = h('div', { class: 'helplist' });
  const input = h('input', { placeholder: '搜索：比如“对称”“资源池”“保存”', oninput: () => render(input.value.trim()) });
  const render = (q) => {
    list.innerHTML = '';
    for (const [k, e] of Object.entries(HELP)) {
      const text = e.t + e.s + (e.b || '') + (e.tips || []).join('');
      if (q && !text.includes(q)) continue;
      list.append(h('button', { class: 'helpitem', onclick: () => showHelp(k) }, h('b', {}, e.t), h('span', {}, e.s || '')));
    }
  };
  render('');
  modal('帮助中心', h('div', {}, input, list), [{ label: '关闭', value: 1 }]);
  setTimeout(() => input.focus(), 50);
}
