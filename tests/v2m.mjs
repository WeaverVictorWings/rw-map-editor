// 手机触屏测试（CDP 多点触控）：node tests/v2m.mjs <样例地图.tmx> <截图目录>
import { createRequire } from 'module';
import fs from 'fs';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PW || 'playwright');
const [, , sample, out = '.'] = process.argv;
const fail = []; const errors = [];
const expect = (c, m) => { console.log(c ? '  ✓' : '  ✗', m); if (!c) fail.push(m); };
const browser = await chromium.launch();
const ctx = await browser.newContext({ locale: 'zh-CN', viewport: { width: 400, height: 860 }, deviceScaleFactor: 2, hasTouch: true, isMobile: true });
const page = await ctx.newPage();
page.on('pageerror', (e) => errors.push(e.message + '\n' + e.stack));
await page.goto(process.env.URL || 'http://localhost:8765/index.html');
await page.waitForFunction(() => window.__rwReady);
await page.evaluate(async (t) => { await window.__rw.loadMapFromText(t, 'sample.tmx'); window.__rw.rend.centerOn(120, 120, 1); }, fs.readFileSync(sample, 'utf8'));
const cdp = await ctx.newCDPSession(page);
const touch = (type, pts) => cdp.send('Input.dispatchTouchEvent', { type, touchPoints: pts.map(([x, y], i) => ({ x, y, id: i })) });
const box = await page.locator('#cv').boundingBox();
const X = (f) => box.x + box.width * f, Y = (f) => box.y + box.height * f;
await page.waitForTimeout(300);
console.log('单指画');
await touch('touchStart', [[X(.3), Y(.4)]]);
for (let i = 1; i <= 8; i++) { await touch('touchMove', [[X(.3 + i * .04), Y(.4 + i * .02)]]); }
await touch('touchEnd', []);
expect(await page.evaluate(() => window.__rw.ed.undoStack.length) === 1, '单指画了一笔');
await page.screenshot({ path: out + '/50-touch-paint.png' });
console.log('双指缩放');
const z0 = await page.evaluate(() => window.__rw.rend.view.z);
await touch('touchStart', [[X(.4), Y(.5)], [X(.6), Y(.5)]]);
for (let i = 1; i <= 6; i++) await touch('touchMove', [[X(.4 - i * .03), Y(.5)], [X(.6 + i * .03), Y(.5)]]);
await touch('touchEnd', []);
const z1 = await page.evaluate(() => window.__rw.rend.view.z);
expect(z1 > z0 * 1.5, `双指放大 ${z0.toFixed(2)} → ${z1.toFixed(2)}`);
expect(await page.evaluate(() => window.__rw.ed.undoStack.length) === 1, '缩放不会多画');
console.log('双指轻点撤销');
await touch('touchStart', [[X(.4), Y(.5)], [X(.6), Y(.5)]]);
await touch('touchEnd', []);
await page.waitForTimeout(100);
expect(await page.evaluate(() => window.__rw.ed.undoStack.length) === 0, '双指轻点撤销');
console.log('三指轻点重做');
await touch('touchStart', [[X(.3), Y(.5)], [X(.5), Y(.5)], [X(.7), Y(.5)]]);
await touch('touchEnd', []);
await page.waitForTimeout(100);
expect(await page.evaluate(() => window.__rw.ed.undoStack.length) === 1, '三指轻点重做');
console.log('手机：放出生点、浮动印章');
await page.click('[data-mode=units]'); await page.waitForTimeout(200);
await page.locator('.tool[data-tool=spawn]').click();
await page.touchscreen.tap(X(.5), Y(.35));
expect(await page.evaluate(() => window.__rw.ed.usedTeams().size) === 21, '出生点 +1');
await page.locator('.dtab', { hasText: '印章' }).click(); await page.waitForTimeout(200);
await page.locator('.stamp').first().click(); await page.waitForTimeout(200);
await touch('touchStart', [[X(.5), Y(.4)]]); await touch('touchMove', [[X(.55), Y(.45)]]); await touch('touchEnd', []);
await page.screenshot({ path: out + '/51-touch-float.png' });
await page.locator('#selbar button.primary').click();
expect(await page.evaluate(() => !window.__rw.ed.floating), '手机放下印章');
await page.click('[data-mode=triggers]'); await page.waitForTimeout(200);
await page.locator('.tpl', { hasText: '城市争夺' }).click(); await page.waitForTimeout(200);
await page.screenshot({ path: out + '/52-phone-city.png' });
await page.locator('.modal .mfoot button.primary').click();
await page.touchscreen.tap(X(.5), Y(.3));
await page.waitForTimeout(300);
await page.locator('.tcard2').first().click(); await page.waitForTimeout(300);
await page.screenshot({ path: out + '/53-phone-trig-editor.png' });
console.log('错误：', errors.length ? errors.join('\n') : '无');
console.log(fail.length ? `失败 ${fail.length} 项` : '全部通过');
await browser.close();
process.exit(fail.length || errors.length ? 1 : 0);
